function polyline(
	points: Array<[number, number]>,
	className: string,
	opacity: number,
): Line[] {
	return points.slice(0, -1).map(([x, y], index) => ({
		x,
		y,
		x2: points[index + 1][0],
		y2: points[index + 1][1],
		className,
		opacity,
		delay: -((index % 11) + 1),
	}));
}
